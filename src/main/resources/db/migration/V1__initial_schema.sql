-- Qaryati baseline schema, PostgreSQL 17, managed exclusively by Flyway.
-- Applies to an empty database; proposed contract pending team approval.
-- Owner confirmed V1 was not shared or applied elsewhere and local Flyway history is empty.
-- Never edit this migration after application. All domain objects explicitly use public.

CREATE TABLE public.governorates (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name_ar VARCHAR(120) NOT NULL UNIQUE,
 name_en VARCHAR(120),
 code VARCHAR(32) UNIQUE
);
CREATE TABLE public.local_authorities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 governorate_id BIGINT NOT NULL REFERENCES public.governorates(id) ON DELETE RESTRICT,
 name_ar VARCHAR(180) NOT NULL,
 name_en VARCHAR(180),
 authority_type VARCHAR(32) NOT NULL CHECK (authority_type IN ('MUNICIPALITY','VILLAGE_COUNCIL','OTHER')),
 UNIQUE(governorate_id,name_ar)
);
CREATE TABLE public.villages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 governorate_id BIGINT NOT NULL REFERENCES public.governorates(id) ON DELETE RESTRICT,
 local_authority_id BIGINT REFERENCES public.local_authorities(id) ON DELETE RESTRICT,
 name_ar VARCHAR(180) NOT NULL,
 name_en VARCHAR(180),
 name_origin TEXT,
 location_description TEXT NOT NULL,
 latitude NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
 longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
 elevation_m NUMERIC(9,2),
 area_km2 NUMERIC(12,3) CHECK (area_km2 > 0),
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','UNDER_REVIEW','VERIFIED','REJECTED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 archived_at TIMESTAMPTZ,
 CONSTRAINT ck_village_coordinates_pair CHECK ((latitude IS NULL) = (longitude IS NULL)),
 CONSTRAINT uq_village_governorate_name UNIQUE(governorate_id,name_ar)
);
-- Enforce that assigned authority belongs to the same governorate as the village.
ALTER TABLE public.local_authorities ADD CONSTRAINT uq_local_authority_governorate UNIQUE(id,governorate_id);
ALTER TABLE public.villages ADD CONSTRAINT fk_village_authority_same_governorate FOREIGN KEY(local_authority_id,governorate_id) REFERENCES public.local_authorities(id,governorate_id);
CREATE TABLE public.village_names (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 name VARCHAR(200) NOT NULL,
 language_code VARCHAR(12) NOT NULL,
 name_type VARCHAR(24) NOT NULL CHECK(name_type IN ('ALTERNATIVE','HISTORICAL','FORMER','TRANSLITERATION')),
 notes TEXT,
 UNIQUE(village_id,name,language_code,name_type)
);
CREATE TABLE public.village_relations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 related_village_id BIGINT REFERENCES public.villages(id) ON DELETE RESTRICT,
 related_place_name VARCHAR(200),
 relation_type VARCHAR(28) NOT NULL CHECK(relation_type IN ('NEARBY','ADJACENT','HISTORICALLY_RELATED','OTHER')),
 distance_km NUMERIC(10,2) CHECK(distance_km >= 0),
 CONSTRAINT ck_relation_target CHECK ((related_village_id IS NOT NULL) <> (related_place_name IS NOT NULL)),
 CONSTRAINT ck_no_self_relation CHECK (related_village_id IS NULL OR related_village_id <> village_id)
);
CREATE TABLE public.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 display_name VARCHAR(160) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 last_login_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_users_email_lower ON public.users(lower(email));
CREATE TABLE public.roles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 description VARCHAR(250)
);
CREATE TABLE public.user_roles (
 user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 role_id BIGINT NOT NULL REFERENCES public.roles(id) ON DELETE RESTRICT,
 PRIMARY KEY(user_id,role_id)
);
CREATE TABLE public.sources (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(350) NOT NULL,
 publisher VARCHAR(200),
 author VARCHAR(200),
 source_type VARCHAR(28) NOT NULL CHECK(source_type IN ('CENSUS','GOVERNMENT','BOOK','ARTICLE','ARCHIVE','WEBSITE','INTERVIEW','OTHER')),
 url TEXT,
 publication_date DATE,
 accessed_at DATE,
 citation TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT ck_source_link CHECK (url IS NULL OR url ~* '^https?://')
);
CREATE TABLE public.population_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 reference_year INTEGER NOT NULL CHECK(reference_year BETWEEN 1800 AND 2200),
 reference_date DATE,
 population_count INTEGER NOT NULL CHECK(population_count >= 0),
 methodology VARCHAR(32) NOT NULL CHECK(methodology IN ('CENSUS','ESTIMATE','REGISTER','OTHER')),
 source_id BIGINT NOT NULL REFERENCES public.sources(id) ON DELETE RESTRICT,
 notes TEXT,
 verification_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(verification_status IN ('DRAFT','UNDER_REVIEW','VERIFIED','REJECTED','DISPUTED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT ck_population_year_date CHECK(reference_date IS NULL OR EXTRACT(YEAR FROM reference_date) = reference_year),
 CONSTRAINT uq_population_observation UNIQUE(village_id,reference_year,methodology,source_id)
);
CREATE TABLE public.village_histories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL UNIQUE REFERENCES public.villages(id) ON DELETE RESTRICT,
 overview TEXT NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 verification_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(verification_status IN ('DRAFT','UNDER_REVIEW','VERIFIED','REJECTED','DISPUTED'))
);
CREATE TABLE public.historical_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 title VARCHAR(250) NOT NULL,
 description TEXT NOT NULL,
 event_date DATE,
 year_from INTEGER CHECK(year_from BETWEEN 1 AND 2200),
 year_to INTEGER CHECK(year_to BETWEEN 1 AND 2200),
 date_precision VARCHAR(16) NOT NULL CHECK(date_precision IN ('EXACT','YEAR','PERIOD','UNKNOWN')),
 verification_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(verification_status IN ('DRAFT','UNDER_REVIEW','VERIFIED','REJECTED','DISPUTED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT ck_history_year_range CHECK(year_to IS NULL OR (year_from IS NOT NULL AND year_to >= year_from)),
 CONSTRAINT ck_history_date_precision CHECK ((date_precision = 'EXACT' AND event_date IS NOT NULL AND year_from IS NULL AND year_to IS NULL) OR (date_precision = 'YEAR' AND year_from IS NOT NULL AND year_to IS NULL AND event_date IS NULL) OR (date_precision = 'PERIOD' AND year_from IS NOT NULL AND year_to IS NOT NULL AND event_date IS NULL) OR (date_precision = 'UNKNOWN' AND event_date IS NULL AND year_from IS NULL AND year_to IS NULL))
);
CREATE TABLE public.heritage_sites (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 name VARCHAR(250) NOT NULL,
 site_type VARCHAR(32) NOT NULL CHECK(site_type IN ('ARCHAEOLOGICAL','TRADITIONAL_BUILDING','SPRING','RELIGIOUS','VIEWPOINT','OTHER')),
 description TEXT,
 latitude NUMERIC(9,6) CHECK(latitude BETWEEN -90 AND 90),
 longitude NUMERIC(9,6) CHECK(longitude BETWEEN -180 AND 180),
 condition_notes TEXT,
 verification_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(verification_status IN ('DRAFT','UNDER_REVIEW','VERIFIED','REJECTED','DISPUTED')),
 CONSTRAINT ck_heritage_coordinates_pair CHECK((latitude IS NULL) = (longitude IS NULL))
);
CREATE TABLE public.cultural_heritage (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 name VARCHAR(200) NOT NULL,
 heritage_type VARCHAR(25) NOT NULL CHECK(heritage_type IN ('CRAFT','FOOD','TRADITION','PRACTICE','OTHER')),
 description TEXT NOT NULL,
 verification_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(verification_status IN ('DRAFT','UNDER_REVIEW','VERIFIED','REJECTED','DISPUTED')),
 UNIQUE(village_id,name,heritage_type)
);
-- Explicit typed association tables avoid generic (table_name,row_id) pseudo-foreign-keys.
CREATE TABLE public.village_sources (
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE CASCADE,
 source_id BIGINT NOT NULL REFERENCES public.sources(id) ON DELETE RESTRICT,
 claim_note TEXT,
 PRIMARY KEY(village_id,source_id)
);
CREATE TABLE public.history_sources (
 village_history_id BIGINT NOT NULL REFERENCES public.village_histories(id) ON DELETE CASCADE,
 source_id BIGINT NOT NULL REFERENCES public.sources(id) ON DELETE RESTRICT,
 PRIMARY KEY(village_history_id,source_id)
);
CREATE TABLE public.event_sources (
 event_id BIGINT NOT NULL REFERENCES public.historical_events(id) ON DELETE CASCADE,
 source_id BIGINT NOT NULL REFERENCES public.sources(id) ON DELETE RESTRICT,
 PRIMARY KEY(event_id,source_id)
);
CREATE TABLE public.heritage_site_sources (
 heritage_site_id BIGINT NOT NULL REFERENCES public.heritage_sites(id) ON DELETE CASCADE,
 source_id BIGINT NOT NULL REFERENCES public.sources(id) ON DELETE RESTRICT,
 PRIMARY KEY(heritage_site_id,source_id)
);
CREATE TABLE public.cultural_heritage_sources (
 cultural_heritage_id BIGINT NOT NULL REFERENCES public.cultural_heritage(id) ON DELETE CASCADE,
 source_id BIGINT NOT NULL REFERENCES public.sources(id) ON DELETE RESTRICT,
 PRIMARY KEY(cultural_heritage_id,source_id)
);
CREATE TABLE public.agricultural_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name_ar VARCHAR(160) NOT NULL UNIQUE,
 name_en VARCHAR(160),
 product_type VARCHAR(25) NOT NULL CHECK(product_type IN ('CROP','LIVESTOCK','PROCESSED_PRODUCT','OTHER'))
);
CREATE TABLE public.village_agriculture (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 product_id BIGINT NOT NULL REFERENCES public.agricultural_products(id) ON DELETE RESTRICT,
 description TEXT,
 importance VARCHAR(16) CHECK(importance IN ('LOW','MEDIUM','HIGH')),
 UNIQUE(village_id,product_id)
);
CREATE TABLE public.economic_activities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 name VARCHAR(200) NOT NULL,
 activity_type VARCHAR(28) NOT NULL CHECK(activity_type IN ('AGRICULTURE','CRAFT','INDUSTRY','TRADE','TOURISM','OTHER')),
 description TEXT,
 UNIQUE(village_id,name,activity_type)
);
CREATE TABLE public.community_facilities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 village_id BIGINT NOT NULL REFERENCES public.villages(id) ON DELETE RESTRICT,
 name VARCHAR(200) NOT NULL,
 facility_type VARCHAR(26) NOT NULL CHECK(facility_type IN ('SCHOOL','CLINIC','LIBRARY','COMMUNITY_CENTER','PARK','SPORTS','OTHER')),
 description TEXT,
 latitude NUMERIC(9,6) CHECK(latitude BETWEEN -90 AND 90),
 longitude NUMERIC(9,6) CHECK(longitude BETWEEN -180 AND 180),
 CONSTRAINT ck_facility_coordinates_pair CHECK((latitude IS NULL) = (longitude IS NULL))
);
-- Disable users rather than delete them. Retain actor IDs and a durable actor label.
-- For system actions, actor_user_id is NULL and actor_label identifies the system actor.
-- Audit history is append-only by application authorization and operations policy.
CREATE TABLE public.audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_user_id BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
 actor_label VARCHAR(160) NOT NULL,
 entity_type VARCHAR(80) NOT NULL,
 entity_id BIGINT NOT NULL,
 action VARCHAR(20) NOT NULL CHECK(action IN ('CREATE','UPDATE','DELETE','VERIFY','REJECT','RESTORE')),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 before_data JSONB,
 after_data JSONB,
 correlation_id VARCHAR(100),
 reason TEXT,
 CONSTRAINT ck_audit_actor CHECK(actor_label ~ '[^[:space:]]')
);
CREATE TABLE public.verification_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type VARCHAR(80) NOT NULL,
 entity_id BIGINT NOT NULL,
 reviewer_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
 decision VARCHAR(20) NOT NULL CHECK(decision IN ('VERIFIED','REJECTED','NEEDS_REVISION')),
 reason TEXT,
 reviewed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE public.data_conflicts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type VARCHAR(80) NOT NULL,
 entity_id BIGINT NOT NULL,
 field_name VARCHAR(100) NOT NULL,
 conflicting_values JSONB NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','IN_REVIEW','RESOLVED')),
 resolution_notes TEXT,
 resolved_by BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 resolved_at TIMESTAMPTZ,
 CONSTRAINT ck_conflict_resolution CHECK (
  (status = 'RESOLVED' AND resolved_at IS NOT NULL AND resolved_by IS NOT NULL
   AND resolution_notes IS NOT NULL AND resolution_notes ~ '[^[:space:]]')
  OR
  (status <> 'RESOLVED' AND resolved_at IS NULL AND resolved_by IS NULL AND resolution_notes IS NULL)
 ),
 CONSTRAINT ck_conflict_resolution_chronology CHECK(resolved_at IS NULL OR resolved_at >= created_at)
);
-- Operational integration cache; never stores authentication tokens, provider secrets or personal data.
CREATE TABLE public.geocoding_cache (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provider VARCHAR(64) NOT NULL,
 query_hash CHAR(64) NOT NULL,
 response_json JSONB NOT NULL,
 cached_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 expires_at TIMESTAMPTZ NOT NULL,
 UNIQUE(provider,query_hash),
 CONSTRAINT ck_cache_expiry CHECK(expires_at > cached_at)
);

